#!/usr/bin/env bash
# Keeps the Next.js app's design assets in lockstep with the prototype: theme, fonts, motion layer, school directory.
set -euo pipefail
cd "$(cd "$(dirname "$0")" && pwd)/.."
mkdir -p public/fonts src/data
cp prototype/fonts/*.woff2 public/fonts/
cp prototype/motion.js public/motion.js
cp prototype/schoolmap.js public/schoolmap.js
cp data/tn-christian-schools-2026-27.json src/data/schools.json
{
  echo '/* Generated by scripts/sync-web.sh from prototype/theme.css. Edit the prototype theme, then re-run. */'
  echo '@font-face { font-family: "Libre Caslon Display"; font-weight: 400; font-display: swap; src: url(/fonts/caslon-display.woff2) format("woff2"); }'
  echo '@font-face { font-family: "Libre Caslon Text"; font-weight: 400; font-display: swap; src: url(/fonts/caslon-text-400.woff2) format("woff2"); }'
  echo '@font-face { font-family: "Libre Caslon Text"; font-style: italic; font-weight: 400; font-display: swap; src: url(/fonts/caslon-text-400i.woff2) format("woff2"); }'
  echo '@font-face { font-family: "Libre Caslon Text"; font-weight: 700; font-display: swap; src: url(/fonts/caslon-text-700.woff2) format("woff2"); }'
  echo '@font-face { font-family: "Libre Franklin"; font-weight: 100 900; font-display: swap; src: url(/fonts/franklin.woff2) format("woff2"); }'
  cat prototype/theme.css
  cat <<'CSS'
/* app-only additions */
.form-actions { display: flex; justify-content: space-between; align-items: center; gap: 12px; flex-wrap: wrap; padding-top: 22px; border-top: 1px solid var(--line); }
main { display: block; }
.notice { padding: 12px 16px; border-radius: var(--r-sm); font-size: 15px; }
.notice-ok { background: var(--ok-bg); color: var(--ok); border-left: 3px solid var(--ok); }
.notice-bad { background: var(--bad-bg); color: var(--bad); border-left: 3px solid var(--bad); }
.wrap-narrow { max-width: 760px; margin: 0 auto; }
CSS
} > src/app/globals.css
echo synced
