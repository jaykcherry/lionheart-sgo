"""Builds prototype/schools.js and data/*.json from the TDOE-derived school list (data/tn-christian-schools-2026-27.psv).
Needs: pip install zipcodes"""
import csv, json, re, zipcodes
rows = list(csv.DictReader(open('data/tn-christian-schools-2026-27.psv'), delimiter='|'))
# Stable IDs used by the prototype's demo portals.
DEMO = {'Christ Presbyterian Academy': 'cpa', 'Davidson Academy': 'da', 'Donelson Christian Academy': 'dca', 'Ezell-Harding Christian School': 'ehcs', 'Goodpasture Christian School': 'gcs', 'Lipscomb Academy': 'la', 'Nashville Christian School: Charlotte Pike': 'ncs', 'Friendship Christian School': 'fcs', 'Brentwood Academy': 'ba', 'Middle Tennessee Christian School': 'mtcs', 'Briarcrest Christian School': 'bcs', 'Evangelical Christian School - Middle & Upper School': 'ecs'}
# Email domains that can't prove someone works at a specific school.
GENERIC = {'gmail.com', 'yahoo.com', 'hotmail.com', 'me.com', 'gccsda.com', 'gccsda.org', 'kytn.net', 'outlook.com', 'icloud.com'}
WEST = {'Shelby', 'Fayette', 'Tipton', 'Madison', 'Hardin'}
EAST = {'Blount', 'Knox', 'Hamilton', 'Hamblen', 'Jefferson', 'Sullivan', 'Washington', 'Carter', 'Greene', 'Sevier', 'Bradley', 'McMinn', 'Loudon', 'Anderson', 'Campbell', 'Claiborne', 'Rhea', 'Marion', 'Sequatchie', 'Cumberland'}
def root(host):
    host = host.split('/')[0].lower()
    if not host: return ''
    if 'adventistschoolconnect' in host: return host
    p = host.split('.')
    return '.'.join(p[-3:]) if host.endswith('.tn.org') else '.'.join(p[-2:])
seen, out = {}, []
for r in rows:
    sid = DEMO.get(r['name']) or re.sub(r'[^a-z0-9]+', '-', r['name'].lower()).strip('-')[:40]
    if sid in seen: seen[sid] += 1; sid = f'{sid}-{seen[sid]}'
    else: seen[sid] = 1
    z = zipcodes.matching(r['zip'])[0]
    dom = root(r['website']); em = r['email_domain']
    alt = em if em and em not in GENERIC and em != dom else ''
    if not dom and alt: dom, alt = alt, ''
    reg = 'West' if r['county'] in WEST else 'East' if r['county'] in EAST else 'Middle'
    out.append({'id': sid, 'name': r['name'], 'city': r['city'], 'county': r['county'], 'zip': r['zip'], 'region': reg, 'cat': r['category'], 'auth': r['authorizer'], 'grades': r['grades'], 'k12': int(r['k12_students'] or 0), 'site': r['website'], 'domain': dom, 'alt': alt, 'lat': round(float(z['lat']), 3), 'lon': round(float(z['long']), 3)})
open('prototype/schools.js', 'w').write('/* Tennessee Department of Education, Non-Public Schools Directory 2026-27 (updated Oct 5, 2026): Christian schools in Categories I, II and III with a Tennessee address. Generated by scripts/build-schools.py. */\nwindow.LH_SCHOOLS = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
open('data/tn-christian-schools-2026-27.json', 'w').write(json.dumps(out, indent=1, ensure_ascii=False))
print(len(out), 'schools')
